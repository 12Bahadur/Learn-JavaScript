let firstNumber = prompt("Введите первое число", '');
let secondNumber = prompt("Введите второе число", '');

alert(parseInt(firstNumber) + parseInt(secondNumber)); //сложение
alert(parseInt(firstNumber) - parseInt(secondNumber)); //вычитание
alert(parseInt(firstNumber) * parseInt(secondNumber)); //умножение
alert(parseInt(firstNumber) / parseInt(secondNumber)); //деление